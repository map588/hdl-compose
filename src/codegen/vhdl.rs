    fn generic_width_schematic(width_override: Option<&str>) -> (Schematic, Vec<ModuleDef>) {
        let mut s = Schematic::new("top", Language::Vhdl);
        // Top entity port whose type carries the child's WIDTH-1 expression.
        let derived_range = PortType::StdLogicVector(Range {
            high: RangeExpr::Expr("WIDTH-1".into()),
            low: RangeExpr::Literal(0),
            dir: RangeDir::Downto,
        });
        s.top_ports.push(PortDef {
            name: "dout".into(),
            direction: Direction::Out,
            port_type: derived_range.clone(),
            bundle: None,
        });
        s.top_ports.push(PortDef {
            name: "internal_load".into(),
            direction: Direction::In,
            port_type: derived_range.clone(),
            bundle: None,
        });
        s.add_instance("u_drv", "drv").unwrap();
        s.add_instance("u_load", "drv").unwrap();
        if let Some(w) = width_override {
            s.set_generic_map_entry("u_drv", "WIDTH", w).unwrap();
            s.set_generic_map_entry("u_load", "WIDTH", w).unwrap();
        }
        s.set_port_map_entry("u_drv", "bus", Some(NetRef::TopPort("dout".into())))
            .unwrap();
        // Wire u_load.in_bus to u_drv.bus to force an internal-net signal.
        s.set_port_map_entry(
            "u_load",
            "in_bus",
            Some(NetRef::InstancePort("u_drv".into(), "bus".into())),
        )
        .unwrap();

        let lib = vec![ModuleDef {
            name: "drv".into(),
            generics: vec![GenericDef {
                name: "WIDTH".into(),
                type_name: "integer".into(),
                default_value: Some("8".into()),
            }],
            ports: vec![
                PortDef {
                    name: "bus".into(),
                    direction: Direction::Out,
                    port_type: derived_range.clone(),
                    bundle: None,
                },
                PortDef {
                    name: "in_bus".into(),
                    direction: Direction::In,
                    port_type: derived_range,
                    bundle: None,
                },
            ],
            source_path: "drv.vhd".into(),
            source_hash: 0,
            dependencies: Vec::new(),
        }];

        (s, lib)
    }

