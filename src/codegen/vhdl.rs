/// Generate structural VHDL from a schematic.
pub fn generate_vhdl(
    schematic: &Schematic,
    library: &[ModuleDef],
    diagnostics: &[Diagnostic],
) -> Result<String, CodegenError> {
    check_errors(diagnostics)?;
    check_no_dirty_instances(schematic)?;

    let lib_map: HashMap<&str, &ModuleDef> = library.iter().map(|m| (m.name.as_str(), m)).collect();

    let mut out = String::new();

    // Header comment
    writeln!(
        out,
        "-- Generated by hdl-compose. Edit the source .hdlc project file, not this file."
    )
    .unwrap();
    writeln!(out).unwrap();

    // Library/use
    writeln!(out, "library ieee;").unwrap();
    writeln!(out, "use ieee.std_logic_1164.all;").unwrap();
    writeln!(out).unwrap();

    // Entity declaration
    emit_entity(&mut out, schematic, library);

    writeln!(out).unwrap();

    // Architecture
    writeln!(out, "architecture structural of {} is", schematic.top_name).unwrap();
    writeln!(out).unwrap();

    // Signal declarations: top-port intermediates first (every connected
    // non-inout top port gets its own signal, so internal references all use
    // the intermediate name and no port_map maps directly to the entity port).
    let top_intermediates = collect_top_intermediates(schematic, library);
    for ti in &top_intermediates {
        let type_str = port_type_to_vhdl_signal(&ti.port_type);
        writeln!(out, "  signal {} : {};", ti.sig_name, type_str).unwrap();
    }
    if !top_intermediates.is_empty() {
        writeln!(out).unwrap();
    }

    // Internal nets (instance-driven nets shared across the design).
    let internal_nets = collect_internal_nets(schematic, library);
    for (_, sig_name, port_type) in &internal_nets {
        let type_str = port_type_to_vhdl_signal(port_type);
        writeln!(out, "  signal {sig_name} : {type_str};").unwrap();
    }
    if !internal_nets.is_empty() {
        writeln!(out).unwrap();
    }

    // Component declarations
    let mut seen_modules = Vec::new();
    let mut sorted_instances: Vec<&Instance> = schematic.instances.iter().collect();
    sorted_instances.sort_by(|a, b| a.name.cmp(&b.name));

    for inst in &sorted_instances {
        if !seen_modules.contains(&inst.module_ref) {
            if let Some(module) = lib_map.get(inst.module_ref.as_str()) {
                emit_component(&mut out, module);
                writeln!(out).unwrap();
            }
            seen_modules.push(inst.module_ref.clone());
        }
    }

    writeln!(out, "begin").unwrap();
    writeln!(out).unwrap();

    // Top-port pass-through assignments. Inputs feed the intermediate from the
    // entity port; outputs feed the entity port from the intermediate.
    for ti in &top_intermediates {
        match ti.direction {
            Direction::In => {
                writeln!(out, "  {} <= {};", ti.sig_name, ti.port_name).unwrap();
            }
            Direction::Out => {
                writeln!(out, "  {} <= {};", ti.port_name, ti.sig_name).unwrap();
            }
            Direction::InOut => {}
        }
    }
    if !top_intermediates.is_empty() {
        writeln!(out).unwrap();
    }

    // Instance statements (alphabetical)
    for inst in &sorted_instances {
        if let Some(module) = lib_map.get(inst.module_ref.as_str()) {
            emit_instance(&mut out, schematic, inst, module);
            writeln!(out).unwrap();
        }
    }

    writeln!(out, "end architecture structural;").unwrap();

    Ok(out)
}

fn emit_entity(out: &mut String, schematic: &Schematic, library: &[ModuleDef]) {
    writeln!(out, "entity {} is", schematic.top_name).unwrap();

    // Generics
    if !schematic.top_generics.is_empty() {
        writeln!(out, "  generic (").unwrap();
        for (i, g) in schematic.top_generics.iter().enumerate() {
            let sep = if i < schematic.top_generics.len() - 1 {
                ";"
            } else {
                ""
            };
            if let Some(default) = &g.default_value {
                writeln!(
                    out,
                    "    {} : {} := {}{}",
                    g.name, g.type_name, default, sep
                )
                .unwrap();
            } else {
                writeln!(out, "    {} : {}{}", g.name, g.type_name, sep).unwrap();
            }
        }
        writeln!(out, "  );").unwrap();
    }

    // Ports
    if !schematic.top_ports.is_empty() {
        writeln!(out, "  port (").unwrap();
        for (i, p) in schematic.top_ports.iter().enumerate() {
            let sep = if i < schematic.top_ports.len() - 1 {
                ";"
            } else {
                ""
            };
            let dir = match p.direction {
                Direction::In => "in",
                Direction::Out => "out",
                Direction::InOut => "inout",
            };
            let resolved_type = match find_top_port_context(schematic, library, &p.name) {
                Some((mg, gm)) => resolve_port_type(&p.port_type, mg, gm),
                None => p.port_type.clone(),
            };
            let type_str = port_type_to_vhdl(&resolved_type);
            writeln!(out, "    {} : {} {}{}", p.name, dir, type_str, sep).unwrap();
        }
        writeln!(out, "  );").unwrap();
    }

    writeln!(out, "end entity {};", schematic.top_name).unwrap();
}

fn emit_component(out: &mut String, module: &ModuleDef) {
    writeln!(out, "  component {} is", module.name).unwrap();

    if !module.generics.is_empty() {
        writeln!(out, "    generic (").unwrap();
        for (i, g) in module.generics.iter().enumerate() {
            let sep = if i < module.generics.len() - 1 {
                ";"
            } else {
                ""
            };
            if let Some(default) = &g.default_value {
                writeln!(
                    out,
                    "      {} : {} := {}{}",
                    g.name, g.type_name, default, sep
                )
                .unwrap();
            } else {
                writeln!(out, "      {} : {}{}", g.name, g.type_name, sep).unwrap();
            }
        }
        writeln!(out, "    );").unwrap();
    }

    if !module.ports.is_empty() {
        writeln!(out, "    port (").unwrap();
        for (i, p) in module.ports.iter().enumerate() {
            let sep = if i < module.ports.len() - 1 { ";" } else { "" };
            let dir = match p.direction {
                Direction::In => "in",
                Direction::Out => "out",
                Direction::InOut => "inout",
            };
            let type_str = port_type_to_vhdl(&p.port_type);
            writeln!(out, "      {} : {} {}{}", p.name, dir, type_str, sep).unwrap();
        }
        writeln!(out, "    );").unwrap();
    }

    writeln!(out, "  end component {};", module.name).unwrap();
}

fn emit_instance(out: &mut String, schematic: &Schematic, inst: &Instance, module: &ModuleDef) {
    write!(out, "  {} : {}", inst.name, inst.module_ref).unwrap();

    // Generic map
    if !inst.generic_map.is_empty() {
        writeln!(out).unwrap();
        writeln!(out, "    generic map (").unwrap();
        let mut generics: Vec<_> = inst.generic_map.iter().collect();
        generics.sort_by_key(|(k, _)| {
            module
                .generics
                .iter()
                .position(|g| g.name == **k)
                .unwrap_or(usize::MAX)
        });

        for (i, (name, value)) in generics.iter().enumerate() {
            let sep = if i < generics.len() - 1 { "," } else { "" };
            writeln!(out, "      {} => {}{}", name, value, sep).unwrap();
        }
        writeln!(out, "    )").unwrap();
    } else {
        writeln!(out).unwrap();
    }

    // Port map
    writeln!(out, "    port map (").unwrap();
    // Emit ports in module declaration order
    for (i, port) in module.ports.iter().enumerate() {
        let sep = if i < module.ports.len() - 1 { "," } else { "" };
        let rhs = match inst.port_map.get(&port.name) {
            Some(Some(net_ref)) => render_rhs_vhdl(schematic, net_ref),
            Some(None) | None => "open".to_string(),
        };
        let lhs = match inst.consumer_slices.get(&port.name) {
            Some(SliceExpr::Bit(b)) => format!("{}({})", port.name, b),
            Some(SliceExpr::Range { high, low }) => {
                format!("{}({} downto {})", port.name, high, low)
            }
            None => port.name.clone(),
        };
        writeln!(out, "      {} => {}{}", lhs, rhs, sep).unwrap();
    }
    writeln!(out, "    );").unwrap();
}

/// Render a NetRef as a VHDL association RHS. Slice variants use
/// `(i)` for a single bit and `(high downto low)` for a range.
fn render_rhs_vhdl(schematic: &Schematic, net_ref: &NetRef) -> String {
    let base_name = schematic.signal_name(net_ref);
    match net_ref {
        NetRef::TopPort(_) | NetRef::InstancePort(_, _) => base_name,
        NetRef::TopPortSlice(_, slice) | NetRef::InstancePortSlice(_, _, slice) => {
            match slice {
                SliceExpr::Bit(i) => format!("{base_name}({i})"),
                SliceExpr::Range { high, low } => {
                    format!("{base_name}({high} downto {low})")
                }
            }
        }
    }
}

